-- =====================================================================
-- SnowVillage 受注デモ: 01 基盤オブジェクト作成
--   ロール / ウェアハウス / データベース / スキーマ / ステージ
--   すべて IF NOT EXISTS。CREATE OR REPLACE は使用しない（既存定義を保護）。
-- 実行者: USERADMIN（ロール作成）→ SYSADMIN（WH/DB作成）→ 所有権を APP_OWNER へ移譲
-- =====================================================================

-- ---------- ロール ----------
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS SNOWVILLAGE_APP_OWNER_ROLE COMMENT = 'SnowVillage demo: 開発・所有者ロール';
CREATE ROLE IF NOT EXISTS SNOWVILLAGE_VIEWER_ROLE    COMMENT = 'SnowVillage demo: アプリ利用者ロール';

-- ロール階層: OWNER -> SYSADMIN（管理者が管理できるように）
GRANT ROLE SNOWVILLAGE_APP_OWNER_ROLE TO ROLE SYSADMIN;
GRANT ROLE SNOWVILLAGE_VIEWER_ROLE    TO ROLE SNOWVILLAGE_APP_OWNER_ROLE;

-- ---------- ウェアハウス / DB ----------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS SNOWVILLAGE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'SnowVillage demo warehouse (X-SMALL, auto suspend 60s)';

CREATE DATABASE IF NOT EXISTS SNOWVILLAGE_DB COMMENT = 'SnowVillage demo: PDF発注書の受注データ化';

-- 所有権を専用ロールへ（以降のオブジェクトは APP_OWNER が作成・所有）
GRANT OWNERSHIP ON DATABASE  SNOWVILLAGE_DB TO ROLE SNOWVILLAGE_APP_OWNER_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE SNOWVILLAGE_WH TO ROLE SNOWVILLAGE_APP_OWNER_ROLE COPY CURRENT GRANTS;

USE ROLE SNOWVILLAGE_APP_OWNER_ROLE;
USE WAREHOUSE SNOWVILLAGE_WH;
USE DATABASE SNOWVILLAGE_DB;

CREATE SCHEMA IF NOT EXISTS SNOWVILLAGE_RAW  COMMENT = '受付・AI抽出の生データ';
CREATE SCHEMA IF NOT EXISTS SNOWVILLAGE_CORE COMMENT = 'マスタ・標準化受注・検証・監査';
CREATE SCHEMA IF NOT EXISTS SNOWVILLAGE_APP  COMMENT = 'Streamlitアプリ・参照ビュー';

-- PDF保存ステージ: AI_EXTRACT/TO_FILE はサーバーサイド暗号化が必要
CREATE STAGE IF NOT EXISTS SNOWVILLAGE_DB.SNOWVILLAGE_RAW.SNOWVILLAGE_PDF_STAGE
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = '受付PDF原本（受付ID単位のパス）';

-- アプリコード保存ステージ
CREATE STAGE IF NOT EXISTS SNOWVILLAGE_DB.SNOWVILLAGE_APP.SNOWVILLAGE_APP_STAGE
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Streamlitアプリのソースコード';
