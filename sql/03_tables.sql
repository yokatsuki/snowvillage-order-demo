-- ================= APP 層: 参照ビュー =================
-- 確定受注のみ（処理途中・下書きは含まない）
CREATE VIEW IF NOT EXISTS SNOWVILLAGE_APP.SNOWVILLAGE_V_CONFIRMED_ORDERS AS
SELECT h.ORDER_ID, h.DOCUMENT_ID, h.VERSION_NO, h.ORDER_NUMBER, h.ORDER_DATE, h.CUSTOMER_ID,
       c.OFFICIAL_NAME AS CUSTOMER_NAME, h.DELIVERY_DATE, h.DELIVERY_ADDRESS,
       h.SUBTOTAL, h.TAX_AMOUNT, h.TOTAL_AMOUNT, h.NOTES, h.CONFIRMED_BY, h.CONFIRMED_AT,
       l.LINE_NO, l.CUSTOMER_PRODUCT_CODE, l.PRODUCT_CODE, p.PRODUCT_NAME AS OWN_PRODUCT_NAME,
       l.PRODUCT_NAME AS ORDERED_PRODUCT_NAME, l.SPECIFICATION, l.QUANTITY, l.UNIT,
       l.STANDARD_QUANTITY, p.STANDARD_UNIT, l.UNIT_PRICE, l.LINE_AMOUNT, l.TAX_RATE
FROM SNOWVILLAGE_CORE.SNOWVILLAGE_ORDER_HEADERS h
JOIN SNOWVILLAGE_CORE.SNOWVILLAGE_ORDER_LINES l ON l.ORDER_ID = h.ORDER_ID
LEFT JOIN SNOWVILLAGE_CORE.SNOWVILLAGE_CUSTOMERS c ON c.CUSTOMER_ID = h.CUSTOMER_ID
LEFT JOIN SNOWVILLAGE_CORE.SNOWVILLAGE_PRODUCTS p ON p.PRODUCT_CODE = l.PRODUCT_CODE
WHERE h.ORDER_STATUS = 'CONFIRMED';

-- 受付単位の完全性（受付記録を起点に処理結果を左結合）
CREATE VIEW IF NOT EXISTS SNOWVILLAGE_APP.SNOWVILLAGE_V_DOCUMENT_PIPELINE AS
SELECT d.DOCUMENT_ID, d.ORIGINAL_FILENAME, d.UPLOADED_AT, d.UPLOADED_BY, d.STATUS, d.STATUS_UPDATED_AT,
       d.STAGE_VERIFIED, d.DUPLICATE_OF, d.LAST_ERROR, d.SHA256,
       r.RUNS_TOTAL, r.RUNS_SUCCEEDED, r.RUNS_FAILED, r.LAST_RUN_AT,
       o.ORDER_ID AS LATEST_ORDER_ID, o.ORDER_NUMBER, o.CUSTOMER_ID, o.ORDER_STATUS AS LATEST_ORDER_STATUS,
       o.LAST_VALIDATION_LEVEL, cf.CONFIRMED_ORDER_ID, cf.CONFIRMED_AT,
       CASE
         WHEN d.STATUS = 'DUPLICATE' THEN '重複'
         WHEN d.STATUS = 'SUPERSEDED' THEN '訂正版で置換済'
         WHEN NOT d.STAGE_VERIFIED THEN '保存未確認'
         WHEN COALESCE(r.RUNS_TOTAL,0) = 0 THEN '未抽出'
         WHEN COALESCE(r.RUNS_SUCCEEDED,0) = 0 THEN '抽出失敗'
         WHEN d.STATUS = 'FAILED' THEN '処理失敗（再処理待ち）'
         WHEN d.STATUS IN ('UPLOADED','RECEIVING','EXTRACTING') THEN '処理中・未完了'
         WHEN o.ORDER_ID IS NULL THEN '受注データ欠落'
         WHEN cf.CONFIRMED_ORDER_ID IS NOT NULL AND d.STATUS = 'CONFIRMED' THEN '確定済'
         WHEN o.LAST_VALIDATION_LEVEL IS NULL THEN '未検証'
         WHEN o.LAST_VALIDATION_LEVEL = 'ERROR' THEN '確認待ち(ERROR)'
         ELSE '確定待ち'
       END AS COMPLETENESS_STATE
FROM SNOWVILLAGE_RAW.SNOWVILLAGE_DOCUMENTS d
LEFT JOIN (SELECT DOCUMENT_ID, COUNT(*) RUNS_TOTAL,
                  COUNT_IF(STATUS='SUCCEEDED') RUNS_SUCCEEDED, COUNT_IF(STATUS='FAILED') RUNS_FAILED,
                  MAX(STARTED_AT) LAST_RUN_AT
           FROM SNOWVILLAGE_RAW.SNOWVILLAGE_EXTRACTION_RUNS GROUP BY 1) r ON r.DOCUMENT_ID = d.DOCUMENT_ID
LEFT JOIN (SELECT * FROM SNOWVILLAGE_CORE.SNOWVILLAGE_ORDER_HEADERS
           WHERE ORDER_STATUS IN ('DRAFT','CONFIRMED')
           QUALIFY ROW_NUMBER() OVER (PARTITION BY DOCUMENT_ID ORDER BY VERSION_NO DESC) = 1) o
       ON o.DOCUMENT_ID = d.DOCUMENT_ID
LEFT JOIN (SELECT DOCUMENT_ID, ORDER_ID CONFIRMED_ORDER_ID, CONFIRMED_AT
           FROM SNOWVILLAGE_CORE.SNOWVILLAGE_ORDER_HEADERS WHERE ORDER_STATUS = 'CONFIRMED') cf
       ON cf.DOCUMENT_ID = d.DOCUMENT_ID;
